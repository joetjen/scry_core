# Generator source for `lib/scry_core/grammar/compiled.ex` -- that file
# is generated, checked in, and must never be hand-edited (see its own
# banner). Run this script (`mix run priv/gen/generate_compiled_grammar.exs`)
# after changing `priv/grammar.aether`, then re-run the test suite.
# There's no automatic staleness check between the two (a byte-diff
# between two separately-generated copies of the same grammar
# spuriously fails -- the codegen backend iterates `%Aether.Grammar{}`'s
# own maps, whose iteration order isn't stable across VM boots) --
# matches `mix ichor.gen`'s own documented, deliberate posture on this
# exact point. `grammar_parity_test.exs` is the safety net instead.
#
# Why a manually-run `.exs` script, not a `mix ichor.gen`-style Mix task
# or an automatic Mix compiler (`compilers: [...]`): either of those
# would have to be a real, discoverable compiled module living under
# this package's own `elixirc_paths`, which gets compiled unconditionally
# whenever `scry_core` is built -- including as someone else's
# dependency, where `ichor` (an `only: [:dev, :test]` dependency of
# *this* package) is dropped by Mix regardless of the downstream
# package's own env (`mix.exs`'s own deps comment has the empirical
# finding). A plain script run via `mix run`, only ever invoked in this
# package's own top-level dev context, sidesteps that entirely -- it's
# never compiled as part of anyone's build, dependency or otherwise.
# Mirrors `mix ichor.gen`'s own approach (`ichor/lib/mix/tasks/ichor.gen.ex`)
# near-verbatim -- that task is the documented, recommended path for
# "a grammar compiled ahead of time, not `ichor` present at runtime,"
# just packaged as a Mix task instead of a plain script, since it has
# no core-vs-fragment merge step of its own to do first the way this
# one does (`ScryTimeSeries.Grammar`'s own copy of this script has that
# extra step; this one doesn't need it since there's nothing to merge
# core with).

{:ok, source} = File.read(ScryCore.Grammar.grammar_path())

body = Ichor.generate(source, ScryCore.Grammar.grammar_path(), ScryCore.Actions)

# `publicize/1`: every `defp` the codegen backend emits becomes `def` --
# through `use Ichor` these come from macro expansion, which Elixir's
# unused-function check doesn't flag even when a grammar's own shape
# leaves some unreferenced (e.g. a predefined token no rule actually
# uses); written out as ordinary checked-in source under
# `--warnings-as-errors`, the same `defp`s would trip that check.
# Identical to `Mix.Tasks.Ichor.Gen`'s own `publicize/1`.
publicize = fn body ->
  Macro.postwalk(body, fn
    {:defp, meta, args} -> {:def, meta, args}
    other -> other
  end)
end

text =
  quote do
    defmodule ScryCore.Grammar.Compiled do
      @moduledoc false
      unquote(publicize.(body))
    end
  end
  |> Macro.to_string()
  |> Code.format_string!()
  |> IO.iodata_to_binary()

banner = """
# Generated by:
#
#     mix run priv/gen/generate_compiled_grammar.exs
#
# Do not edit by hand -- edit priv/grammar.aether, then rerun the
# command above and the test suite instead.
"""

out = Path.join(__DIR__, "../../lib/scry_core/grammar/compiled.ex") |> Path.expand()
File.mkdir_p!(Path.dirname(out))
File.write!(out, banner <> text <> "\n")
Mix.shell().info("* creating #{out}")
